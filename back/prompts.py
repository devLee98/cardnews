def _render_stages() -> str:
    blocks = []

    for stage in CARD_STAGES:
        lines = [
            f"### {stage['stage']}  ({stage['group']}{', 핵심' if stage['core'] else ''})",
            f"- 목적: {stage['purpose']}",
            f"- 필수 데이터: {', '.join(stage['required']) or '없음 (맥락에 맞게 직접 작성)'}",
            f"- 활용 가능 데이터: {', '.join(stage['optional']) or '없음'}",
        ]

        if stage["constraint"]:
            lines.append(f"- 제약: {stage['constraint']}")

        blocks.append("\n".join(lines))

    return "\n\n".join(blocks)


def build_plan_prompt(
    inventory_table: str,
    missing_paths: list[str],
    comparison_summary: str = "",
) -> str:
    """구성안 생성용 user 프롬프트."""

    parts = [
        "## 단계 목록",
        _render_stages(),
        "",
        "## 업로드된 데이터에 무엇이 있는지",
        "`채움`은 그 경로가 나오는 자리 중 값이 들어 있는 자리의 수다 (3/15 처럼 읽는다).",
        "`항목수`는 배열인 경우 전체 길이다.",
        "배열은 `[]` 로 합쳐서 한 줄로 보여준다.",
        "",
        "```",
        inventory_table,
        "```",
        "",
        "단계 목록의 데이터 이름과 위 표의 경로는 표기가 같다.",
        "`source_keys` 에는 위 표에 있는 경로를 그대로 쓴다. 경로를 새로 만들지 않는다.",
    ]

    if missing_paths:
        parts += [
            "",
            "## 값이 전부 비어 있는 경로",
            ", ".join(missing_paths),
            "이 경로들은 데이터가 없는 것으로 보고 판단한다.",
        ]

    # 비교표는 위 표에 경로가 없다. 문구 단계에서 걸러 낸 뒤 따로 넘어가기 때문이다.
    # 그래도 어떤 소재가 얼마나 있는지는 알아야 '근거' 같은 카드를 넣을지 판단할 수 있다.
    if comparison_summary:
        parts += [
            "",
            "## 비교표로 받쳐 줄 수 있는 것",
            comparison_summary,
        ]

    return "\n".join(parts)


